"""Builds lang_data.js: what the language check (lang.js) knows of German,
English, French and Italian. From wordfreq (pip install wordfreq), whose word
frequencies come from Wikipedia, subtitles, news, books, web text and Twitter
(data CC BY-SA 4.0, https://github.com/rspeer/wordfreq):

- the most frequent words of each language, with their frequency (as
  -10 * log10 of the share of running words, rounded), and
- for words not on the list, how likely each language spells a word that way:
  letter trigrams of its listed words, so "Velostation" reads German and
  "offertory" English though neither is listed.

    py tools/lang_build.py

German keeps the most words: the engine also asks whether the rest of a
compound is a German word ("Offert|ory" is not). The others only need enough
to tell a sentence is not German.
"""
import json, math, re
from collections import Counter, defaultdict
from pathlib import Path
import wordfreq

SIZES = {'de': 20000, 'en': 10000, 'fr': 5000, 'it': 5000}
DETECT = 10000      # German words past this are for compounds only: equal lists for German and English
LANGS = list(SIZES)
LETTERS = re.compile(r'[^\W\d_]+')
OUT = Path(__file__).resolve().parent.parent / 'lang_data.js'

data = {}
for lang, N in SIZES.items():
    # wordfreq's words, split as the engine splits text (runs of letters): "don't"
    # adds to "don" and "t"
    freq = Counter()
    for w in wordfreq.top_n_list(lang, N * 2, wordlist='large'):
        f = wordfreq.word_frequency(w, lang, wordlist='large')
        for piece in LETTERS.findall(w.lower()):
            freq[piece] += f
    top = freq.most_common(N)
    listed = sum(f for _, f in top[:DETECT])
    cut = round(-10 * math.log10(top[min(DETECT, N) - 1][1]))     # the dearest word detection reads
    words = defaultdict(list)                       # cost -> words
    for w, f in top:
        words[round(-10 * math.log10(f))].append(w)
    # letter trigrams of the listed words, each word once: unlisted words are
    # rare ones, spelled like the language's words, not like its commonest
    tri, ctx = Counter(), Counter()
    for w, _ in top:
        s = '^^' + w + '$'
        for i in range(len(s) - 2):
            tri[s[i:i + 3]] += 1
            ctx[s[i:i + 2]] += 1
    alphabet = len({c for w, _ in top for c in w}) + 1
    # add-one smoothing: P(c | ab) = (n(abc) + 1) / (n(ab) + alphabet)
    grams = {g: round(-10 * math.log10((n + 1) / (ctx[g[:2]] + alphabet))) for g, n in tri.items() if n > 1}
    data[lang] = {
        'words': {str(k): ' '.join(v) for k, v in sorted(words.items())},
        'oov': round(-10 * math.log10(max(1e-6, 1 - listed)), 1),   # share of running words not read as listed
        'cut': cut,
        'ctx': {g: round(10 * math.log10(n + alphabet), 1) for g, n in ctx.items() if n > 1},
        'alphabet': alphabet,
        'grams': grams,
    }

js = ('// Generated by tools/lang_build.py from wordfreq (data CC BY-SA 4.0,\n'
      '// https://github.com/rspeer/wordfreq): see lang.js. Do not edit by hand.\n'
      # as a JSON string: parsed faster than the same object written as JavaScript
      'globalThis.HD_LANG_DATA = JSON.parse(' + json.dumps(json.dumps(data, ensure_ascii=False, separators=(',', ':')), ensure_ascii=False) + ');\n')
OUT.write_text(js, encoding='utf-8')
print(f'{OUT.name}: {len(js) // 1024} KB, words per language: {SIZES}')
